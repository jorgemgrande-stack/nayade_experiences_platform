/**
 * Especificación comercial de cada producto del catálogo (una por clave, sin duplicados).
 *
 * Complementa a la semilla (`elephantSourceV1.ts`) y NO repite lo que ya está en ella: nombre, familia,
 * descripción corta, precio, unidad, periodicidad, dependencias, cupos, capacidades y estados salen siempre del
 * catálogo. Aquí va lo que el catálogo no tiene: descripción completa, problema, inclusiones y exclusiones,
 * implantación, integraciones, estado funcional verificado, contenido público y SEO.
 *
 * Reglas (las comprueba `validateSpecs`):
 *  - ningún texto lleva importes: los precios solo viven en el catálogo;
 *  - lo que no existe se dice («sin desarrollo», «se porta desde…»), nunca se presenta como activación inmediata;
 *  - las referencias F-… son las del MAPA_FUNCIONAL_Y_SOLUCIONES_SECTORIALES_BIG_ELEPHANT.md.
 */

export type SpecCategory = "plan" | "sector_module" | "sector_bundle" | "extension" | "extension_bundle" | "extra" | "capacity" | "service";
/** 1 activable (código en el Core) · 2 portable (desarrollo en otro repositorio o parcial) · 3 desarrollo nuevo. */
export type ImplementationLevel = 1 | 2 | 3;
/** Grado verificado: en uso, parcial, prototipo o diseño, sin desarrollo. */
export type FunctionalGrade = "in_use" | "partial" | "prototype" | "none";
export type Cta = "demo" | "contact" | "waitlist";

export interface ProductSpec {
  key: string;
  category: SpecCategory;
  longDescription: string;
  problem: string;
  forWho: string;
  includes: string[];
  excludes: string[];
  /** Extensiones recomendadas o compatibles (claves). */
  compatibleExtensions: string[];
  capacityRules: string[];
  implementation: { level: ImplementationLevel; requirements: string[]; sources: string[] };
  integrations: string[];
  verified: { grade: FunctionalGrade; evidence: string };
  publicContent: { headline: string; benefits: string[]; cta: Cta };
  seo: { slug: string; title: string; description: string };
  admin: { pendingDecisions: string[]; notes?: string };
  /**
   * Ficha del marketplace del panel (Elephant Connect y Net). Opcional: sin ella, la importación conserva lo que ya
   * tenga el borrador. Un texto que contenga «PENDIENTE» nunca va a la ficha pública: queda como decisión pendiente.
   */
  marketplace?: MarketplaceSpec;
}

export interface MarketplaceSpec {
  valueProposition?: string;
  coreIntegration?: string[];
  terms?: { commitment?: string; cancellation?: string; activation?: string };
  faq?: Array<{ q: string; a: string }>;
  related?: string[];
  /** Solo imágenes reales en https de un almacén público. */
  media?: { cover?: { src: string; alt: string }; screenshots?: Array<{ src: string; alt: string; caption?: string }> };
}

