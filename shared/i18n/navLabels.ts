const BY_LOCALE: Partial<Record<Locale, Record<string, string>>> = { de: NAV_LABELS_DE };

/** Etiqueta del menú en el idioma pedido; sin traducción, el texto original (español). */
export function navLabel(label: string, locale: Locale): string;
export function navLabel(label: string | null, locale: Locale): string | null;
export function navLabel(label: string | null, locale: Locale): string | null {
  if (label === null) return null;
  return BY_LOCALE[locale]?.[label] ?? label;
}

/** Traduce en bloque secciones, entradas y subentradas de un menú ya resuelto (sin tocar rutas, claves ni permisos). */
export function localizeNav<S extends { label: string | null; items: Array<{ label: string; children?: Array<{ label: string }> }> }>(sections: S[], locale: Locale): S[] {
  if (locale === "es") return sections;
  return sections.map((s) => ({
    ...s,
    label: navLabel(s.label, locale),
    items: s.items.map((i) => ({
      ...i,
      label: navLabel(i.label, locale),
      ...(i.children ? { children: i.children.map((c) => ({ ...c, label: navLabel(c.label, locale) })) } : {}),
    })),
  }));
}
