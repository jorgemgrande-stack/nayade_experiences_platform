export function localizeIntegrationText<T extends string | null | undefined>(text: T, locale: Locale): T {
  if (locale !== "de" || !text) return text;
  const tr = (s: string): string => {
    if (DE[s] !== undefined) return DE[s];
    for (const [re, fn] of PATTERNS) {
      const m = s.match(re);
      if (m) return fn(m, tr);
    }
    return s;
  };
  return tr(text as string) as T;
}

